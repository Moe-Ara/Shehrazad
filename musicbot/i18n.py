CATALOGS: dict[str, dict[str, str]] = {"en": EN}


def resolve_locale(setting: str | None, discord_locale: str | None) -> str:
    """The bot replies in English only, whatever the server setting or Discord locale."""
    return "en"


def t(locale: str, key: str, **params: object) -> str:
    template = CATALOGS.get(locale, EN).get(key) or EN.get(key)
    if template is None:
        log.warning("missing translation key %s", key)
        return key
    try:
        return template.format(**params)
    except (KeyError, IndexError, ValueError):
        log.warning("bad parameters for translation key %s", key)
        return template
