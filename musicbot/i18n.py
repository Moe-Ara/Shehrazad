CATALOGS: dict[str, dict[str, str]] = {"en": EN, "ar": AR}


def resolve_locale(setting: str | None, discord_locale: str | None) -> str:
    """Server setting wins unless it's 'auto'; otherwise follow the Discord locale."""
    if setting and setting != "auto" and setting in SUPPORTED:
        return setting
    if discord_locale:
        base = str(discord_locale).split("-")[0].lower()
        if base in SUPPORTED:
            return base
    return "en"


def t(locale: str, key: str, **params: object) -> str:
    template = CATALOGS.get(locale, EN).get(key) or EN.get(key)
    if template is None:
        log.warning("missing translation key %s", key)
        return key
    try:
        return template.format(**params)
    except (KeyError, IndexError, ValueError):
        log.warning("bad parameters for translation key %s", key)
        return template
